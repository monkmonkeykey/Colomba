let currentFrame = 0
let lastFrameDrawn = -1
let isLooping = false
let totalFrames = 7

function showCurrentFrame() {
    if (currentFrame == lastFrameDrawn) {
        return
    }

    if (currentFrame == 0) {
        drawFrame0()
    } else if (currentFrame == 1) {
        drawFrame1()
    } else if (currentFrame == 2) {
        drawFrame2()
    } else if (currentFrame == 3) {
        drawFrame3()
    } else if (currentFrame == 4) {
        drawFrame4()
    } else if (currentFrame == 5) {
        drawFrame5()
    } else if (currentFrame == 6) {
        drawFrame6()
    }

    lastFrameDrawn = currentFrame
}

OLED12864_I2C.init(60)
OLED12864_I2C.zoom(false)
OLED12864_I2C.clear()
OLED12864_I2C.draw()
showCurrentFrame()

input.onButtonPressed(Button.A, function () {
    if (isLooping) {
        return
    }
    currentFrame += -1
    if (currentFrame < 0) {
        currentFrame = totalFrames - 1
    }
    showCurrentFrame()
})

input.onButtonPressed(Button.B, function () {
    if (isLooping) {
        return
    }
    currentFrame += 1
    if (currentFrame >= totalFrames) {
        currentFrame = 0
    }
    showCurrentFrame()
})

input.onButtonPressed(Button.AB, function () {
    isLooping = !isLooping
})

basic.forever(function () {
    if (isLooping) {
        currentFrame += 1
        if (currentFrame >= totalFrames) {
            currentFrame = 0
        }
        showCurrentFrame()
        basic.pause(80)
    } else {
        basic.pause(20)
    }
})