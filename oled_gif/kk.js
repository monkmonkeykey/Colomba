let currentFrame = 0
let lastFrameDrawn = -1
let isLooping = false
let totalFrames = 1

function showCurrentFrame() {
    if (currentFrame == lastFrameDrawn) {
        return
    }

    if (currentFrame == 0) {
        drawFrame0()
    }

    lastFrameDrawn = currentFrame
}

OLED12864_I2C.init(60)
OLED12864_I2C.zoom(false)
OLED12864_I2C.clear()
OLED12864_I2C.draw()
showCurrentFrame()

input.onButtonPressed(Button.A, function () {
    if (isLooping) {
        return
    }
    currentFrame += -1
    if (currentFrame < 0) {
        currentFrame = totalFrames - 1
    }
    showCurrentFrame()
})

input.onButtonPressed(Button.B, function () {
    if (isLooping) {
        return
    }
    currentFrame += 1
    if (currentFrame >= totalFrames) {
        currentFrame = 0
    }
    showCurrentFrame()
})

input.onButtonPressed(Button.AB, function () {
    isLooping = !isLooping
})

basic.forever(function () {
    if (isLooping) {
        currentFrame += 1
        if (currentFrame >= totalFrames) {
            currentFrame = 0
        }
        showCurrentFrame()
        basic.pause(80)
    } else {
        basic.pause(20)
    }
})